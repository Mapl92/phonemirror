/// Übersetzt macOS-Tastencodes (`NSEvent.keyCode`, ANSI-Layout) in HID-Usages der Keyboard-Page (0x07).
/// Das iPhone interpretiert die Usages mit seinem eigenen Tastaturlayout – wie eine angeschlossene Hardwaretastatur.
public enum KeyMapping {
    public static func hidUsage(forMacKeyCode keyCode: UInt16) -> UInt16? {
        table[keyCode]
    }

    /// HID-Usage für eine Modifier-Taste (`NSEvent.keyCode` bei `flagsChanged`).
    public static func isModifier(_ keyCode: UInt16) -> Bool {
        modifierKeyCodes.contains(keyCode)
    }

    private static let modifierKeyCodes: Set<UInt16> = [0x37, 0x36, 0x38, 0x3C, 0x3A, 0x3D, 0x3B, 0x3E, 0x39]

    private static let table: [UInt16: UInt16] = [
        // Buchstaben
        0x00: 0x04, 0x0B: 0x05, 0x08: 0x06, 0x02: 0x07, 0x0E: 0x08, 0x03: 0x09, 0x05: 0x0A, 0x04: 0x0B,
        0x22: 0x0C, 0x26: 0x0D, 0x28: 0x0E, 0x25: 0x0F, 0x2E: 0x10, 0x2D: 0x11, 0x1F: 0x12, 0x23: 0x13,
        0x0C: 0x14, 0x0F: 0x15, 0x01: 0x16, 0x11: 0x17, 0x20: 0x18, 0x09: 0x19, 0x0D: 0x1A, 0x07: 0x1B,
        0x10: 0x1C, 0x06: 0x1D,
        // Ziffern 1–9, 0
        0x12: 0x1E, 0x13: 0x1F, 0x14: 0x20, 0x15: 0x21, 0x17: 0x22, 0x16: 0x23, 0x1A: 0x24, 0x1C: 0x25,
        0x19: 0x26, 0x1D: 0x27,
        // Steuertasten
        0x24: 0x28, // Return
        0x35: 0x29, // Escape
        0x33: 0x2A, // Delete (Backspace)
        0x30: 0x2B, // Tab
        0x31: 0x2C, // Space
        0x1B: 0x2D, 0x18: 0x2E, 0x21: 0x2F, 0x1E: 0x30, 0x2A: 0x31, // - = [ ] \
        0x29: 0x33, 0x27: 0x34, 0x32: 0x35, 0x2B: 0x36, 0x2F: 0x37, 0x2C: 0x38, // ; ' ` , . /
        0x0A: 0x64, // ISO-Taste links neben Z (deutsches < >)
        0x39: 0x39, // Caps Lock
        0x75: 0x4C, // Forward Delete
        0x73: 0x4A, 0x77: 0x4D, 0x74: 0x4B, 0x79: 0x4E, // Home End PageUp PageDown
        0x7C: 0x4F, 0x7B: 0x50, 0x7D: 0x51, 0x7E: 0x52, // Pfeile rechts links runter hoch
        // Modifier
        0x3B: 0xE0, 0x38: 0xE1, 0x3A: 0xE2, 0x37: 0xE3, // links: Control Shift Option Command
        0x3E: 0xE4, 0x3C: 0xE5, 0x3D: 0xE6, 0x36: 0xE7, // rechts
    ]
}
